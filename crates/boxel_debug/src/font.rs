/// The glyph of `c`; characters outside printable ASCII render as `?`.
pub fn glyph(c: char) -> &'static [u8; 8] {
    let index = u32::from(c)
        .checked_sub(FIRST)
        .filter(|&i| (i as usize) < FONT.len())
        .unwrap_or(u32::from('?') - FIRST);
    &FONT[index as usize]
}

/// How [`layout_text`] places and colors the text.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TextStyle {
    /// Top-left corner of the background box, in pixels.
    pub origin: [f32; 2],
    /// Screen pixels per font pixel.
    pub scale: f32,
    /// Font pixels between two lines.
    pub line_gap: f32,
    /// Font pixels between the box edge and the text.
    pub padding: f32,
    /// Text color (linear RGBA).
    pub color: [f32; 4],
    /// Background box color (linear RGBA); alpha 0 skips the box.
    pub background: [f32; 4],
}

impl Default for TextStyle {
    fn default() -> Self {
        Self {
            origin: [8.0, 8.0],
            scale: 2.0,
            line_gap: 2.0,
            padding: 3.0,
            color: [1.0, 1.0, 1.0, 1.0],
            background: [0.0, 0.0, 0.0, 0.6],
        }
    }
}

/// Appends the background box (first) and the text of `lines` to `out`. Each horizontal run of
/// lit pixels in a glyph row becomes one rectangle.
pub fn layout_text<S: AsRef<str>>(lines: &[S], style: &TextStyle, out: &mut Vec<OverlayRect>) {
    let s = style.scale;
    let cell = GLYPH_SIZE as f32 * s;
    let line_height = (GLYPH_SIZE as f32 + style.line_gap) * s;
    let pad = style.padding * s;
    let columns = lines
        .iter()
        .map(|l| l.as_ref().chars().count())
        .max()
        .unwrap_or(0);
    if style.background[3] > 0.0 && columns > 0 {
        let [x, y] = style.origin;
        out.push(OverlayRect {
            min: [x, y],
            max: [
                x + 2.0 * pad + columns as f32 * cell,
                y + 2.0 * pad + lines.len() as f32 * line_height - style.line_gap * s,
            ],
            color: style.background,
        });
    }
    let left = style.origin[0] + pad;
    for (row_index, line) in lines.iter().enumerate() {
        let top = style.origin[1] + pad + row_index as f32 * line_height;
        for (column, c) in line.as_ref().chars().enumerate() {
            let x0 = left + column as f32 * cell;
            for (y, &bits) in glyph(c).iter().enumerate() {
                let y0 = top + y as f32 * s;
                let mut bit = 0;
                while bit < GLYPH_SIZE {
                    if bits & (1 << bit) == 0 {
                        bit += 1;
                        continue;
                    }
                    let start = bit;
                    while bit < GLYPH_SIZE && bits & (1 << bit) != 0 {
                        bit += 1;
                    }
                    out.push(OverlayRect {
                        min: [x0 + start as f32 * s, y0],
                        max: [x0 + bit as f32 * s, y0 + s],
                        color: style.color,
                    });
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_lookup_covers_printable_ascii_and_falls_back_to_question_mark() {
        assert_eq!(glyph(' '), &[0; 8]);
        assert_eq!(glyph('A'), &FONT[usize::from(b'A' - b' ')]);
        assert_eq!(glyph('~'), &FONT[FONT.len() - 1]);
        assert_eq!(glyph('\u{7f}'), glyph('?'));
        assert_eq!(glyph('\u{e9}'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
    }

    #[test]
    fn layout_emits_the_box_then_one_rect_per_run() {
        let style = TextStyle::default();
        let mut out = Vec::new();
        // '-' is one row with a single run of 6 pixels; ' ' has no pixels.
        layout_text(&["- -"], &style, &mut out);
        assert_eq!(out.len(), 3, "{out:?}");
        let pad = style.padding * style.scale;
        assert_eq!(out[0].min, style.origin);
        assert_eq!(out[0].max[0], style.origin[0] + 2.0 * pad + 3.0 * 16.0);
        assert_eq!(out[0].color, style.background);
        let first = out[1];
        assert_eq!(first.max[0] - first.min[0], 6.0 * style.scale);
        assert_eq!(first.max[1] - first.min[1], style.scale);
        assert_eq!(out[2].min[0] - out[1].min[0], 2.0 * 8.0 * style.scale);

        // Second line starts one line height lower; no background without text.
        out.clear();
        layout_text(&[".", "."], &style, &mut out);
        assert_eq!(out.len(), 5, "box + 2 rows per '.'");
        let line_height = (8.0 + style.line_gap) * style.scale;
        assert_eq!(out[3].min[1] - out[1].min[1], line_height);
        out.clear();
        layout_text::<&str>(&[], &style, &mut out);
        assert!(out.is_empty());
    }
}
