/// The glyph rows of `c`, if the font has it.
pub fn glyph(c: char) -> Option<&'static [u8; 8]> {
    let code = u32::from(c);
    match code {
        0x20..=0x7E => BASIC.get((code - BASIC_FIRST) as usize),
        0xA0..=0xFF => EXT_LATIN.get((code - EXT_LATIN_FIRST) as usize),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spanish_letters_are_there() {
        for c in "áéíóúñüÁÉÍÓÚÑÜ¿¡".chars() {
            let rows = glyph(c).unwrap_or_else(|| panic!("{c} missing"));
            assert!(rows.iter().any(|&r| r != 0), "{c} is empty");
        }
        assert_eq!(glyph('A'), Some(&BASIC[usize::from(b'A' - b' ')]));
        assert_eq!(glyph('\u{7f}'), None);
        assert_eq!(glyph('\u{100}'), None);
        assert_eq!(glyph(' '), Some(&[0; 8]));
    }
}
